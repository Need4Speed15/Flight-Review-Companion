// Disposable local-D1 integration test. Refuses non-loopback origins.
import assert from 'node:assert/strict';
const origin=new URL(process.argv[2]||'http://127.0.0.1:4388').origin;
if(!['127.0.0.1','localhost','[::1]'].includes(new URL(origin).hostname))throw new Error('Use an isolated loopback preview only.');
let response=await fetch(origin+'/api/identity');
assert.equal(response.status,200);
assert.equal((await response.json()).authenticated,false);
assert.equal((await fetch(origin+'/api/sync')).status,401);
response=await fetch(origin+'/signin-with-chatgpt?return_to=/',{redirect:'manual'});
assert.ok([302,303,307].includes(response.status));
const cookie=response.headers.get('set-cookie')?.split(';')[0];assert.ok(cookie);
const headers={cookie,origin,'Content-Type':'application/json'};
const identity=await (await fetch(origin+'/api/identity',{headers})).json();
assert.equal(identity.authenticated,true);assert.equal(identity.user.id,'local_seedy');assert.equal(identity.storageAvailable,true);
headers['X-Study-User']=identity.user.id;
assert.equal((await fetch(origin+'/api/sync',{headers:{...headers,'X-Study-User':'another-account'}})).status,409);
const timestamp=Date.now(),key='mix:api-integration-test';
response=await fetch(origin+'/api/sync',{method:'POST',headers,body:JSON.stringify({records:{[key]:{value:{name:'Local API integration test',counts:{ifr:1}},updatedAt:timestamp,opId:'test-new'}}})});
assert.equal(response.status,200);
assert.equal((await response.json()).records[key].value.name,'Local API integration test');
response=await fetch(origin+'/api/sync',{method:'POST',headers,body:JSON.stringify({records:{[key]:{value:{name:'STALE'},updatedAt:timestamp-1,opId:'test-old'}}})});
assert.equal(response.status,200);
assert.equal((await response.json()).records[key].value.name,'Local API integration test','Actual D1 upsert must reject stale records');
assert.equal((await fetch(origin+'/api/sync',{method:'POST',headers:{...headers,origin:'https://other.example'},body:JSON.stringify({records:{}})})).status,403);
response=await fetch(origin+'/api/reports',{method:'POST',headers,body:JSON.stringify({cardId:'IFR-102',concern:'Disposable local QA report: verify that the source is shown.'})});
assert.equal(response.status,201);
assert.ok((await response.json()).id);
assert.equal((await fetch(origin+'/api/reports',{headers})).status,identity.isOwner?200:403);
response=await fetch(origin+'/');assert.equal(response.status,200);assert.match(await response.text(),/Flight Review/);
for(const asset of ['script.js','cards.js','styles.css','study-store.js','source-enhancements.js'])assert.equal((await fetch(origin+'/'+asset)).status,200,asset);
console.log('PASS: real local Vinext/D1 anonymous and signed-in identity, sync storage, stale-update protection, cross-origin rejection, persisted report submission, owner gating, root HTML and static assets.');
